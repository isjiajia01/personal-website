import json, math, sys
A="ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
LC,LR,LF=64,36,120
def n(x,y):
    s=math.sin(x*127.1+y*311.7)*43758.5453; return s-math.floor(s)
def vn(x,y):
    xi,yi=math.floor(x),math.floor(y);xf,yf=x-xi,y-yi
    u=xf*xf*(3-2*xf);v=yf*yf*(3-2*yf)
    a,b,c,d=n(xi,yi),n(xi+1,yi),n(xi,yi+1),n(xi+1,yi+1)
    return a+(b-a)*u+(c-a)*v+(a-b-c+d)*u*v
vals=[]
for f in range(LF):
    t=f/LF
    for y in range(LR):
        for x in range(LC):
            u,v=x/LC,y/LR
            cx=0.5+0.3*math.cos(t*2*math.pi); cy=0.55-0.25*math.sin(t*2*math.pi)  # looping sun
            sun=max(0,1-math.hypot((u-cx)*1.8,v-cy)*2.6)
            # clouds drift horizontally and loop seamlessly
            c=0
            for o,sc in ((0,3),(1,6)):
                ang=t*2*math.pi
                c+=(0.6 if o==0 else 0.4)*vn(u*sc+math.cos(ang)*1.5+o*7,v*sc*1.6+math.sin(ang)*1.5)
            cloud=max(0,min(1,(c-0.45)*3))
            L=0.25+0.45*cloud*(1-v*0.3)+0.6*sun**1.5
            if v>0.78: L=0.12+0.1*vn(u*20,v*20)   # dark skyline strip
            vals.append(max(0,min(63,round(L*63))))
def delta(vs,stride):
    out=[]
    for i,v in enumerate(vs):
        out.append(A[v] if i<stride else A[(v-vs[i-stride])&63])
    return "".join(out)
L=delta(vals,LC*LR)
MC,MR=128,72
cit=[]
for y in range(MR):
    for x in range(MC):
        v=y/MR
        r,g,b=(0.95-0.3*v,0.55+0.1*v-0.2*v*v,0.35+0.45*v) if v<0.78 else (0.12,0.1,0.14)
        cit+= [A[round(k*63)] for k in (r,g,b)]
json.dump({"LF":LF,"playFps":24,"LC":LC,"LR":LR,"MCOLS":MC,"MROWS":MR,"enc":"delta1","LUMA":L,"CITYC":"".join(cit),"source":"generated by gen-scene.py (original synthetic scene)"},open(sys.argv[1],"w"),separators=(",",":"))
